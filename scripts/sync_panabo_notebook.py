"""Embed the canonical Panabo generator/reference and plain-language guidance."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def embedded_source():
    source = (ROOT/"scripts/generate_panabo.py").read_text(encoding="utf-8")
    source = source.split('if __name__ == "__main__":')[0].rstrip()
    reference = json.loads((ROOT/"data/panabo_reference.json").read_text(encoding="utf-8"))
    return ("# Generated by scripts/sync_panabo_notebook.py; edit the canonical script/reference.\n"
            + source + "\n\nPANABO_REFERENCE = " + repr(reference) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT/"Panabo_Area_Demand_Forecastingg.ipynb"
    notebook = json.loads(path.read_text(encoding="utf-8"))
    cell = next((c for c in notebook["cells"] if c["id"] == "panabo-city-generator"), None)
    expected = embedded_source()
    guidance = ("# Generated by scripts/sync_panabo_notebook.py; edit scripts/notebook_guidance.py.\n"
                + (ROOT/"scripts/notebook_guidance.py").read_text(encoding="utf-8"))
    guidance_cell = next((c for c in notebook["cells"] if c["id"] == "guidance-functions"), None)
    if args.check:
        if cell is None or cell["source"] != expected:
            raise SystemExit("Embedded Panabo generator/reference is out of sync.")
        if guidance_cell is None or guidance_cell["source"] != guidance:
            raise SystemExit("Embedded notebook guidance is out of sync.")
        print("Embedded Panabo generator/reference and guidance match canonical sources.")
        return
    if cell is None:
        cell = {"cell_type":"code", "execution_count":None, "id":"panabo-city-generator",
                "metadata":{"tags":["functions", "panabo_generator"]}, "outputs":[], "source":expected}
        index = next(i for i,c in enumerate(notebook["cells"]) if "load" in c["metadata"].get("tags", []))
        notebook["cells"].insert(index, cell)
    else:
        cell["source"] = expected
    if guidance_cell is None:
        index = next(i for i,c in enumerate(notebook["cells"]) if "load" in c["metadata"].get("tags", []))
        notebook["cells"].insert(index, {"cell_type":"code", "execution_count":None,
            "id":"guidance-functions", "metadata":{"tags":["functions"]}, "outputs":[], "source":guidance})
    else:
        guidance_cell["source"] = guidance
    path.write_text(json.dumps(notebook, indent=1, ensure_ascii=False)+"\n", encoding="utf-8")
    print("Updated standalone Panabo generator/reference and guidance cells.")


if __name__ == "__main__":
    main()
